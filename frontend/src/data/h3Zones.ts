import { H3Zone } from '../types';

function createHexagonCoordinates(centerLat: number, centerLon: number, radius = 0.012): [number, number][] {
  const points: [number, number][] = [];
  for (let i = 0; i < 6; i++) {
    const angle = (Math.PI / 3) * i + Math.PI / 6;
    const lat = centerLat + (radius * 0.85) * Math.sin(angle);
    const lon = centerLon + radius * Math.cos(angle);
    points.push([Number(lat.toFixed(5)), Number(lon.toFixed(5))]);
  }
  return points;
}

