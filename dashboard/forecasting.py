def export_forecasting_dashboard_html(output_path: Optional[Path] = None) -> Path:
    """Generate and save the forecasting dashboard as a static HTML file."""
    output_path = output_path or (REPORTS_DIR / "forecasting_dashboard.html")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    html_content = build_forecasting_dashboard_html()
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(html_content)
    return output_path


@router.get("/forecasting", response_class=HTMLResponse)
def get_forecasting_dashboard():
    """Serve the interactive forecasting dashboard web page."""
    return HTMLResponse(content=build_forecasting_dashboard_html())
