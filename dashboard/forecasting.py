from fastapi import APIRouter
from fastapi.responses import HTMLResponse

from config.settings import settings

router = APIRouter(prefix="/dashboard", tags=["forecasting_dashboard"])

REPORTS_DIR = settings.BASE_DIR / "reports" / "models"


def load_model_metrics() -> Dict[str, Any]:
    """Load metrics.json generated by the forecasting pipeline."""
    metrics_path = REPORTS_DIR / "metrics.json"
    if metrics_path.exists():
        with open(metrics_path, "r") as f:
            return json.load(f)
    return {}


def load_baseline_results() -> pd.DataFrame:
    """Load baseline_results.csv."""
    csv_path = REPORTS_DIR / "baseline_results.csv"
    if csv_path.exists():
        return pd.read_csv(csv_path)
    return pd.DataFrame()


def load_feature_summary() -> pd.DataFrame:
    """Load feature_summary.csv."""
    csv_path = REPORTS_DIR / "feature_summary.csv"
    if csv_path.exists():
        return pd.read_csv(csv_path)
    return pd.DataFrame()


def build_comparison_chart(df: pd.DataFrame) -> str:
    """Build horizontal bar chart comparing RMSE across models."""
    if df.empty:
        return "<p>No results available</p>"

    sorted_df = df.sort_values("cv_rmse", ascending=True)
    fig = px.bar(
        sorted_df,
        x="cv_rmse",
        y="label",
        orientation="h",
        color="feature_set",
        color_discrete_map={"calendar_only": "#3B82F6", "calendar_weather": "#10B981"},
        labels={"cv_rmse": "Rolling CV RMSE (Lower is Better)", "label": "Model", "feature_set": "Feature Set"},
        title="Baseline Models: Expanding Window CV RMSE",
    )
    fig.update_layout(
        template="plotly_white",
        height=380,
        margin=dict(l=20, r=20, t=40, b=20),
    )
    return fig.to_html(full_html=False, include_plotlyjs=False)


